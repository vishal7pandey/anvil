"""Evidence writer: render the PR body, Jira comment, RTKB page and handoff note from a run's evidence.

The writer subagent fills a plain `evidence` dict (documented in `_FIELDS`); these functions render
the outward-facing Markdown. `publish_evidence` does the live write: Jira comment + label + RTKB page.
"""

from typing import Any

from anvil.tools import confluence, jira

_FIELDS = """\
key            Jira key, e.g. 'RTEMS-1' (required)
summary        one-line summary of the issue
repo           'owner/repo'
branch         the anvil/... working branch
pr_url         pull request URL (after github_open_pr)
root_cause     file:line + why the code was wrong
fix            what changed and why it is sufficient
tests          list of evidence lines: what failed before, what passes after
ci_state       success|failure|pending|none (from github_checks)
ci_url         link to the checks
risk           what else could be affected
run_id         Anvil run id
run_url        link to the run record in the UI/API (optional)
usd            cost in USD (optional)
tokens         total tokens (optional)
duration_min   wall time (optional)
human_touches  count of approvals/interventions (optional)
"""

EVIDENCE_SPACES = {"RTKB", "RTKBTEST"}


def _line(ev: dict, name: str, default: str = "") -> str:
    return str(ev.get(name) or default)


def _metrics(ev: dict) -> str:
    parts = []
    for k, label in (("usd", "$"), ("tokens", " tokens"), ("duration_min", " min"), ("human_touches", " human touches")):
        v = ev.get(k)
        if v is None:
            continue
        parts.append(f"${v:.2f}" if label == "$" else f"{v}{label}")
    return ", ".join(parts)


def pr_body(ev: dict[str, Any]) -> str:
    """PR body: root cause, change, tests, evidence links, run record (contract step 7)."""
    tests = ev.get("tests") or []
    test_lines = "\n".join(f"- {t}" for t in tests) if tests else "- (not recorded)"
    return f"""## Root cause
{_line(ev, "root_cause", "(not recorded)")}

## Fix
{_line(ev, "fix", "(not recorded)")}

## Tests
- Reproduced: {_line(ev, "reproduction", "see evidence below")}
{test_lines}
- CI: {_line(ev, "ci_state", "pending")} {_line(ev, "ci_url")}

## Risk
{_line(ev, "risk", "(not recorded)")}

## Evidence
- Jira: {_line(ev, "key")}{f" ({ev['jira_url']})" if ev.get("jira_url") else ""}
- PR: {_line(ev, "pr_url", "(this pull request)")}
- Confluence: {_line(ev, "evidence_url", "(written after merge)")}
- Run: {_line(ev, "run_id")}{f" ({ev['run_url']})" if ev.get("run_url") else ""}

Generated by Anvil run {_line(ev, "run_id", "(unknown)")}.
"""


def jira_evidence_comment(ev: dict[str, Any]) -> str:
    """Jira comment: root cause, fix, tests, CI links, cost (contract step 9)."""
    tests = ev.get("tests") or []
    test_lines = "\n".join(f"- {t}" for t in tests)
    metrics = _metrics(ev)
    return f"""[anvil] Done in run {_line(ev, "run_id")}{f" ({ev['run_url']})" if ev.get("run_url") else ""}.

**Root cause:** {_line(ev, "root_cause")}
**Fix:** {_line(ev, "fix")}
**Tests:**
{test_lines or "- (not recorded)"}
**CI:** {_line(ev, "ci_state", "pending")} {_line(ev, "ci_url")}
**PR:** {_line(ev, "pr_url")}
**Evidence:** {_line(ev, "evidence_url")}
**Cost:** {metrics or "(not recorded)"}"""


def confluence_evidence(ev: dict[str, Any]) -> tuple[str, str]:
    """RTKB evidence page: title '<KEY> evidence: <summary>', markdown body."""
    title = f"{_line(ev, 'key', 'UNKNOWN')} evidence: {_line(ev, 'summary', '(no summary)')}"
    tests = ev.get("tests") or []
    metrics = _metrics(ev)
    md = f"""# {title}

| | |
|---|---|
| Jira | {_line(ev, "key")}{f" - {_line(ev, 'jira_url')}" if ev.get("jira_url") else ""} |
| Repo / branch | {_line(ev, "repo")} @ {_line(ev, "branch")} |
| PR | {_line(ev, "pr_url")} |
| CI | {_line(ev, "ci_state", "pending")} {_line(ev, "ci_url")} |
| Run | {_line(ev, "run_id")}{f" ({ev['run_url']})" if ev.get("run_url") else ""} |
| Cost | {metrics or "(not recorded)"} |

## Root cause
{_line(ev, "root_cause")}

## Fix
{_line(ev, "fix")}

## Tests
{chr(10).join(f"- {t}" for t in tests) if tests else "- (not recorded)"}

## Risk
{_line(ev, "risk")}

## What the agent learned
{_line(ev, "lesson", "(nothing recorded)")}
"""
    return title, md


def handoff_note(run: dict[str, Any], note: dict[str, Any]) -> str:
    """Handoff note for the Jira comment when the agent is stuck (contract 'Stuck detection')."""
    key = _line(run, "jira_key", _line(run, "key"))
    branch = _line(run, "branch")
    return f"""[anvil] Handing off to a human (run {_line(run, 'run_id')}).

**Ticket:** {key}
**WIP branch:** {branch} (commits kept; sandbox kept 24 h for `docker exec -it anvil-sbx-* bash`)
**Goal:** {_line(note, "goal")}
**What was tried:** {_line(note, "tried")}
**Evidence:** {_line(note, "evidence")}
**Best hypothesis:** {_line(note, "hypothesis")}
**Suggested next step:** {_line(note, "next_step")}"""


def publish_evidence(ev: dict[str, Any], space: str = "RTKB", parent_id: str | None = None) -> dict[str, Any]:
    """Write the evidence package: RTKB page (upsert by title), Jira comment, `anvil-in-review` label.

    Returns the artifact URLs. Outward calls: gate this function (or the calls it makes) under
    the run's approval policy.
    """
    if space.upper() not in EVIDENCE_SPACES:
        from anvil.tools.errors import ToolError

        raise ToolError(f"evidence pages go to {sorted(EVIDENCE_SPACES)}, not '{space}'")
    title, md = confluence_evidence(ev)
    page = confluence.confluence_write(space, title, md, parent_id=parent_id)
    ev = {**ev, "evidence_url": page["url"]}
    comment = jira.jira_comment(ev["key"], jira_evidence_comment(ev))
    labels = jira.jira_set_labels(ev["key"], add=["anvil-in-review"])
    return {"confluence_page": page, "jira_comment": comment, "labels": labels}
